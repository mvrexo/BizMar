-- Run once in Supabase > SQL Editor. Private admin-only backend.
create table if not exists products (
 id bigint generated by default as identity primary key,
 name text not null, category text not null,
 price numeric(12,2) not null default 0 check(price>=0),
 unit_cost numeric(12,2) not null default 0 check(unit_cost>=0),
 image_url text, active boolean not null default true,
 unique(name,category)
);
create table if not exists customers (
 id bigint generated by default as identity primary key,
 name text not null, phone text not null default '', address text not null default '',
 created_at timestamptz not null default now()
);
create table if not exists orders (
 id bigint generated by default as identity primary key,
 customer_id bigint not null references customers(id),
 ordered_at timestamptz not null default now(),
 due_date date not null,
 status text not null default 'Pending' check(status in ('Pending','Confirmed','In Production','Ready','Completed','Cancelled')),
 notes text not null default ''
);
create table if not exists order_items (
 id bigint generated by default as identity primary key,
 order_id bigint not null references orders(id) on delete cascade,
 product_id bigint not null references products(id),
 quantity integer not null check(quantity>0),
 unit_price numeric(12,2) not null check(unit_price>=0),
 unit_cost numeric(12,2) not null check(unit_cost>=0)
);
create table if not exists payments (
 id bigint generated by default as identity primary key,
 order_id bigint not null references orders(id),
 paid_at timestamptz not null default now(),
 amount numeric(12,2) not null check(amount>0),
 method text not null default 'Transfer',
 reference text not null default ''
);
create index if not exists idx_orders_due on orders(due_date);
create index if not exists idx_items_order on order_items(order_id);
create index if not exists idx_payments_order on payments(order_id);
-- Restrict direct browser/client access; app uses server-side service role key.
alter table products enable row level security;
alter table customers enable row level security;
alter table orders enable row level security;
alter table order_items enable row level security;
alter table payments enable row level security;
